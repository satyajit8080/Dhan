"""Generate docs/phase7-meeting-example.md from an OFFLINE SIMULATED meeting.

The agent replies come from tests/ai_fakes.py: deterministic, built only from
the evidence, used to show the pipeline. They are not Grok output and say
nothing about model quality.

    python scripts/phase7_meeting_example.py
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from doi.ai.meetings import MeetingEngine, MemoryMeetingStore  # noqa: E402
from doi.llm.budget import MemoryBudget  # noqa: E402
from doi.llm.gateway import FakeGrokClient, LLMGateway, MemoryCallLog  # noqa: E402
from tests.ai_fakes import claim, scripted  # noqa: E402
from tests.unit.test_feature_engine import AS_OF  # noqa: E402
from tests.unit.test_meetings import ctx  # noqa: E402


def bear(ev):
    return {
        "stance": "BEAR",
        "confidence": 4,
        "claims": [claim(ev, ("oi",))],
        "prediction": {"target": "INDEX", "direction": "DOWN", "horizon_min": 30},
    }


def veto(ev):
    return {
        "veto": True,
        "confidence": 4,
        "flaws": [claim(ev, ("liquidity", "volatility"))],
        "kill_criteria": [claim(ev, ("oi",))],
    }


async def one(title: str, overrides: dict, **kw) -> str:
    g = LLMGateway(FakeGrokClient(scripted(overrides)), MemoryBudget(), MemoryCallLog())
    e = MeetingEngine(g, MemoryMeetingStore())
    r = await e.run(ctx(**kw), AS_OF)
    out = [f"## {title}", "", f"- Meeting `{r.meeting_id}` status **{r.status}**, final action **{r.final_action}**",
           f"- Python overrides: {r.overrides or 'none'}", f"- Disagreements: {json.dumps(r.disagreements) if r.disagreements else 'none'}",
           f"- Pre-registered predictions: {len(r.prediction_ids)}; simulated cost ₹{r.cost_inr:.4f}", "",
           "| # | round | agent | status | stance/action | conf | first claim (evidence refs) |", "|---|---|---|---|---|---|---|"]  # fmt: skip
    for i, (rnd, t) in enumerate(e.store.turn_rows[r.meeting_id], 1):
        o = t.output.model_dump(mode="json") if t.output else {}
        first = next((v[0] for k in ("claims", "flaws", "rationale") if (v := o.get(k))), None)
        stance = o.get("stance") or o.get("action") or ("veto" if o.get("veto") else "") or ("passed" if o.get("passed") else "")
        out.append(f"| {i} | {rnd} | {t.agent_id} | {t.status} | {stance} | {o.get('confidence', '')} | "
                   f"{(first or {}).get('text', '')} ({', '.join((first or {}).get('evidence_refs', []))}) |")  # fmt: skip
    return "\n".join(out) + "\n"


async def main() -> None:
    parts = [
        "# Phase 7 AI meeting examples (OFFLINE SIMULATION)", "",
        "> Generated by `scripts/phase7_meeting_example.py` with deterministic simulated agent replies. They are **not Grok output**.",
        "> They show the workflow, independence, Python authority and recording. No live Grok call has been made from this environment.", "",
    ]  # fmt: skip
    parts.append(await one("A. Consensus: recommendation goes to the human approval queue", {}))
    parts.append(await one("B. Specialists disagree: rebuttal round recorded", {"options_flow": bear}))
    parts.append(await one("C. Contrarian veto with no CIO rebuttal: downgraded to WATCH", {"contrarian": veto}))
    parts.append(
        await one(
            "D. Deterministic RiskGate rejects: risk veto beats the CIO",
            {},
            risk_dry_run={"approved": False, "reasons": ["spread: 3.1% (max 1.0%)"]},
        )
    )
    (ROOT / "docs" / "phase7-meeting-example.md").write_text("\n".join(parts))
    print("wrote docs/phase7-meeting-example.md")


if __name__ == "__main__":
    asyncio.run(main())
